#!/usr/bin/env python3
"""Writes each client's command key table from clients/testdata/commands.json.

The table says, per command, where its keys are among the arguments. Each client reads
it through one small function (its cluster key lookup) and checks that function against
clients/testdata/key_vectors.json in its own tests.

    python3 scripts/gen_client_keys.py           rewrite the six generated files
    python3 scripts/gen_client_keys.py --check   fail when one is out of date (check.sh)

Rule kinds, with the three numbers each one uses (unused numbers are 0):
    NONE           no keys
    RANGE          first, last, step: arguments first..=last every step; a negative last
                   counts from the end (-1 is the last argument)
    NUMKEYS        count_at, before: the argument at count_at is a key count and that many
                   keys follow it; before, when not 0, is one more key ahead of the count
    KEYWORD_HALF   after the argument equal to the keyword (any case), the first half of
                   the remaining arguments
    KEY_AND_STORE  first: argument first, and the argument after any keyword (any case)
Flags are the server's bits: write 1, readonly 2, fast 4, denyoom 8, blocking 16.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "clients" / "testdata" / "commands.json"
KINDS = {"none": 0, "range": 1, "numkeys": 2, "keyword_half": 3, "key_and_store": 4}
FLAGS = {"write": 1, "readonly": 2, "fast": 4, "denyoom": 8, "blocking": 16}
NOTE = "Generated by scripts/gen_client_keys.py from clients/testdata/commands.json. Do not edit."


def rows():
    spec = json.loads(SPEC.read_text())
    out = []
    for command in spec["commands"]:
        keys = command["keys"]
        kind = keys["kind"]
        if kind == "range":
            numbers = (keys["first"], keys["last"], keys["step"])
        elif kind == "numkeys":
            numbers = (keys["count_at"], keys["before"], 0)
        elif kind == "key_and_store":
            numbers = (keys["first"], 0, 0)
        else:
            numbers = (0, 0, 0)
        if kind == "keyword_half":
            words = [keys["keyword"]]
        else:
            words = list(keys.get("keywords", []))
        flags = sum(FLAGS[name] for name in command["flags"])
        out.append((command["name"], KINDS[kind], numbers, words, flags))
    return out


def quoted(words):
    return ", ".join(json.dumps(word) for word in words)


def go(table):
    lines = [
        "// Copyright (c) 2026 Salih Cantekin. MIT License; see LICENSE.",
        "",
        "// Code generated by scripts/gen_client_keys.py from clients/testdata/commands.json. DO NOT EDIT.",
        "",
        "package ruvio",
        "",
        "// commandKeyRule says where a command's keys are among its arguments; see",
        "// scripts/gen_client_keys.py for the meaning of kind and the three numbers.",
        "type commandKeyRule struct {",
        "\tkind     uint8",
        "\ta, b, c  int8",
        "\tkeywords []string",
        "\tflags    uint8",
        "}",
        "",
        "const (",
        "\truleNone uint8 = iota",
        "\truleRange",
        "\truleNumKeys",
        "\truleKeywordHalf",
        "\truleKeyAndStore",
        ")",
        "",
        "var commandKeyRules = map[string]commandKeyRule{",
    ]
    width = max(len(json.dumps(name)) for name, *_ in table) + 1
    for name, kind, (a, b, c), words, flags in table:
        keywords = f"[]string{{{quoted(words)}}}" if words else "nil"
        key = (json.dumps(name) + ":").ljust(width)
        lines.append(f"\t{key} {{{kind}, {a}, {b}, {c}, {keywords}, {flags}}},")
    lines.append("}")
    return "\n".join(lines) + "\n"


def python(table):
    lines = [
        "# MIT License - Copyright (c) 2026 Salih Cantekin. See LICENSE.",
        f'"""{NOTE}',
        "",
        "COMMAND_KEY_RULES maps a command name (upper case) to",
        "(kind, a, b, c, keywords, flags); see scripts/gen_client_keys.py.",
        '"""',
        "",
        "RULE_NONE = 0",
        "RULE_RANGE = 1",
        "RULE_NUMKEYS = 2",
        "RULE_KEYWORD_HALF = 3",
        "RULE_KEY_AND_STORE = 4",
        "",
        "COMMAND_KEY_RULES = {",
    ]
    for name, kind, (a, b, c), words, flags in table:
        keywords = "(" + "".join(f"b{json.dumps(word)}, " for word in words) + ")"
        lines.append(f"    b{json.dumps(name)}: ({kind}, {a}, {b}, {c}, {keywords}, {flags}),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def node(table):
    lines = [
        "// SPDX-License-Identifier: MIT",
        f"// {NOTE}",
        "",
        "/** Where a command's keys are among its arguments; see scripts/gen_client_keys.py. */",
        "export const enum KeyRule { None = 0, Range = 1, NumKeys = 2, KeywordHalf = 3, KeyAndStore = 4 }",
        "",
        "/** [kind, a, b, c, keywords, flags] */",
        "export type CommandKeyRule = readonly [KeyRule, number, number, number, readonly string[], number];",
        "",
        "export const COMMAND_KEY_RULES: ReadonlyMap<string, CommandKeyRule> = new Map<string, CommandKeyRule>([",
    ]
    for name, kind, (a, b, c), words, flags in table:
        lines.append(f"  [{json.dumps(name)}, [{kind}, {a}, {b}, {c}, [{quoted(words)}], {flags}]],")
    lines.append("]);")
    return "\n".join(lines) + "\n"


def rust(table):
    lines = [
        f"// {NOTE}",
        "",
        "/// Where a command's keys are among its arguments; see scripts/gen_client_keys.py.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub(crate) enum KeyRule {",
        "    None,",
        "    Range {",
        "        first: i8,",
        "        last: i8,",
        "        step: i8,",
        "    },",
        "    NumKeys {",
        "        count_at: u8,",
        "        before: u8,",
        "    },",
        "    KeywordHalf {",
        "        keyword: &'static str,",
        "    },",
        "    KeyAndStore {",
        "        first: u8,",
        "        keywords: &'static [&'static str],",
        "    },",
        "}",
        "",
        "/// `(name, rule, flags)`, sorted by name.",
        "#[rustfmt::skip]",
        "pub(crate) static COMMAND_KEY_RULES: &[(&str, KeyRule, u8)] = &[",
    ]
    for name, kind, (a, b, c), words, flags in table:
        if kind == 0:
            rule = "KeyRule::None"
        elif kind == 1:
            rule = f"KeyRule::Range {{ first: {a}, last: {b}, step: {c} }}"
        elif kind == 2:
            rule = f"KeyRule::NumKeys {{ count_at: {a}, before: {b} }}"
        elif kind == 3:
            rule = f"KeyRule::KeywordHalf {{ keyword: {json.dumps(words[0])} }}"
        else:
            rule = f"KeyRule::KeyAndStore {{ first: {a}, keywords: &[{quoted(words)}] }}"
        lines.append(f"    ({json.dumps(name)}, {rule}, {flags}),")
    lines.append("];")
    return "\n".join(lines) + "\n"


def java(table):
    lines = [
        "// SPDX-License-Identifier: MIT",
        f"// {NOTE}",
        "package io.github.salihcantekin.ruvio.internal;",
        "",
        "import java.util.HashMap;",
        "import java.util.Map;",
        "",
        "/** Where each command's keys are among its arguments; see scripts/gen_client_keys.py. */",
        "public final class CommandKeyRules {",
        "    public static final int NONE = 0;",
        "    public static final int RANGE = 1;",
        "    public static final int NUMKEYS = 2;",
        "    public static final int KEYWORD_HALF = 3;",
        "    public static final int KEY_AND_STORE = 4;",
        "",
        "    /** One command's rule: kind, the numbers a, b and c, keywords and server flags. */",
        "    public record Rule(int kind, int a, int b, int c, String[] keywords, int flags) {}",
        "",
        "    /** Upper-case command name to its rule. */",
        "    public static final Map<String, Rule> RULES;",
        "",
        "    static {",
        f"        Map<String, Rule> rules = new HashMap<>({len(table) * 2});",
    ]
    for name, kind, (a, b, c), words, flags in table:
        keywords = f"new String[] {{{quoted(words)}}}" if words else "new String[0]"
        lines.append(f"        rules.put({json.dumps(name)}, new Rule({kind}, {a}, {b}, {c}, {keywords}, {flags}));")
    lines += [
        "        RULES = Map.copyOf(rules);",
        "    }",
        "",
        "    private CommandKeyRules() {}",
        "}",
    ]
    return "\n".join(lines) + "\n"


def csharp(table):
    lines = [
        f"// {NOTE}",
        "using System.Collections.Frozen;",
        "",
        "namespace Ruvio.Client.Cluster;",
        "",
        "/// <summary>Where each command's keys are among its arguments; see scripts/gen_client_keys.py.</summary>",
        "internal static class CommandKeyRules",
        "{",
        "    public const byte None = 0;",
        "    public const byte Range = 1;",
        "    public const byte NumKeys = 2;",
        "    public const byte KeywordHalf = 3;",
        "    public const byte KeyAndStore = 4;",
        "",
        "    internal sealed record Rule(byte Kind, sbyte A, sbyte B, sbyte C, string[] Keywords, byte Flags);",
        "",
        "    /// <summary>Upper-case command name to its rule.</summary>",
        "    public static readonly FrozenDictionary<string, Rule> Rules = new Dictionary<string, Rule>(StringComparer.Ordinal)",
        "    {",
    ]
    for name, kind, (a, b, c), words, flags in table:
        keywords = f"[{quoted(words)}]" if words else "[]"
        lines.append(f"        [{json.dumps(name)}] = new({kind}, {a}, {b}, {c}, {keywords}, {flags}),")
    lines += [
        "    }.ToFrozenDictionary(StringComparer.Ordinal);",
        "}",
    ]
    return "\n".join(lines) + "\n"


TARGETS = {
    "clients/go/command_keys_gen.go": go,
    "clients/python/ruvio/_command_keys.py": python,
    "clients/node/src/command-keys.ts": node,
    "clients/ruvio-client/src/command_keys.rs": rust,
    "clients/java/src/main/java/io/github/salihcantekin/ruvio/internal/CommandKeyRules.java": java,
    "clients/csharp/Ruvio.Client/Cluster/CommandKeyRules.g.cs": csharp,
}


def main():
    check = "--check" in sys.argv[1:]
    table = rows()
    stale = []
    for relative, render in TARGETS.items():
        path = ROOT / relative
        text = render(table)
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(relative)
        else:
            path.write_text(text)
    if stale:
        print("out of date, run python3 scripts/gen_client_keys.py:", *stale, sep="\n  ")
        return 1
    if not check:
        print(f"wrote {len(TARGETS)} files, {len(table)} commands")
    return 0


if __name__ == "__main__":
    sys.exit(main())
