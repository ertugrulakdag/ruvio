using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Ruvio.Client.Generators;

[Generator]
public sealed class RespVerbGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<string> verbs = context.AdditionalTextsProvider
            .Where(static file => file.Path.EndsWith("RespVerbs.txt", StringComparison.Ordinal))
            .Select(static (file, cancellation) => file.GetText(cancellation)?.ToString() ?? "");

        context.RegisterSourceOutput(verbs, static (output, text) =>
        {
            string source = Emit(text);

            output.AddSource("RespVerbs.g.cs", SourceText.From(source, Encoding.UTF8));
        });
    }

    private static string Emit(string text)
    {
        var builder = new StringBuilder();

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("using System;");
        builder.AppendLine();
        builder.AppendLine("namespace Ruvio.Client");
        builder.AppendLine("{");
        builder.AppendLine("    internal static class RespVerbs");
        builder.AppendLine("    {");

        var seen = new HashSet<string>(StringComparer.Ordinal);
        var names = new List<string>();

        foreach (string raw in text.Split(['\r', '\n'], StringSplitOptions.RemoveEmptyEntries))
        {
            string name = raw.Trim();

            if (name.Length == 0 || name.StartsWith("#", StringComparison.Ordinal) || !seen.Add(name))
            {
                continue;
            }

            if (!IsIdentifier(name))
            {
                continue;
            }

            names.Add(name);
            builder.Append("        internal static ReadOnlySpan<byte> ");
            builder.Append(name);
            builder.Append(" => \"");
            builder.Append(name);
            builder.AppendLine("\"u8;");
        }

        builder.AppendLine();
        builder.AppendLine("        internal static ReadOnlySpan<byte> Bulk(string name) => name switch");
        builder.AppendLine("        {");

        foreach (string name in names)
        {
            builder.Append("            \"");
            builder.Append(name);
            builder.Append("\" => \"$");
            builder.Append(Encoding.UTF8.GetByteCount(name).ToString(System.Globalization.CultureInfo.InvariantCulture));
            builder.Append("\\r\\n");
            builder.Append(name);
            builder.AppendLine("\\r\\n\"u8,");
        }

        builder.AppendLine("            _ => default,");
        builder.AppendLine("        };");

        builder.AppendLine("    }");
        builder.AppendLine("}");

        return builder.ToString();
    }

    private static bool IsIdentifier(string name)
    {
        if (name.Length == 0 || !char.IsLetter(name[0]))
        {
            return false;
        }

        for (int index = 1; index < name.Length; index++)
        {
            char character = name[index];
            
            if (!char.IsLetterOrDigit(character) && character != '_')
            {
                return false;
            }
        }

        return true;
    }
}
