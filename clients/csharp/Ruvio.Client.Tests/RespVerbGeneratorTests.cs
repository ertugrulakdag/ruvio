using Xunit;

namespace Ruvio.Client.Tests;

public class RespVerbGeneratorTests
{
    [Fact]
    public void ClientBuildEmitsRespVerbsGCsForTheVerbList()
    {
        string client = FindClientDirectory();
        string verbs = File.ReadAllText(Path.Combine(client, "RespVerbs.txt"));
        string generated = File.ReadAllText(FindGeneratedFile(client));
        string[] names = VerbNames(verbs);

        Assert.Contains("// <auto-generated />", generated, StringComparison.Ordinal);
        Assert.Contains("namespace Ruvio.Client", generated, StringComparison.Ordinal);
        Assert.Contains("internal static class RespVerbs", generated, StringComparison.Ordinal);

        foreach (string name in names)
        {
            Assert.Contains(
                $"internal static ReadOnlySpan<byte> {name} => \"{name}\"u8;",
                generated,
                StringComparison.Ordinal);
            Assert.Contains(
                $"\"{name}\" => \"${System.Text.Encoding.UTF8.GetByteCount(name)}\\r\\n{name}\\r\\n\"u8,",
                generated,
                StringComparison.Ordinal);
        }

        Assert.Equal(names.Length, CountMembers(generated));
    }

    private static string[] VerbNames(string verbs)
    {
        var names = new List<string>();

        foreach (string raw in verbs.Split(new[] { '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries))
        {
            string name = raw.Trim();

            if (name.Length == 0 || name.StartsWith('#'))
            {
                continue;
            }

            names.Add(name);
        }

        return names.ToArray();
    }

    private static int CountMembers(string generated)
    {
        int count = 0;
        int index = 0;

        while ((index = generated.IndexOf("internal static ReadOnlySpan<byte> ", index, StringComparison.Ordinal)) >= 0)
        {
            if (!generated.AsSpan(index).StartsWith("internal static ReadOnlySpan<byte> Bulk(", StringComparison.Ordinal))
                count++;

            index += 4;
        }

        return count;
    }

    private static string FindGeneratedFile(string client)
    {
        string root = Path.Combine(client, "obj");

        if (Directory.Exists(root))
        {
            string[] matches = Directory.GetFiles(root, "RespVerbs.g.cs", SearchOption.AllDirectories);

            if (matches.Length > 0)
            {
                return matches[0];
            }
        }

        throw new FileNotFoundException("The client build did not emit RespVerbs.g.cs.", root);
    }

    internal static string FindClientDirectory()
    {
        string? directory = AppContext.BaseDirectory;

        for (int depth = 0; depth < 8 && directory is not null; depth++)
        {
            string candidate = Path.Combine(directory, "clients", "csharp", "Ruvio.Client");

            if (File.Exists(Path.Combine(candidate, "RespVerbs.txt")))
            {
                return candidate;
            }

            directory = Directory.GetParent(directory)?.FullName;
        }

        throw new FileNotFoundException("Ruvio.Client was not found above the test output.");
    }
}
