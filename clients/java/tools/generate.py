#!/usr/bin/env python3
"""Regenerates Cmd.java (pre-encoded command words) and RuvioSyncCommands.java (blocking facade).

Run from anywhere: python3 clients/java/tools/generate.py
The async command families are the source of truth; the blocking facade mirrors every public
CompletableFuture method of them.
"""
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "main", "java",
                    "io", "github", "salihcantekin", "ruvio")
CHAIN = ["BaseCommands", "StringCommands", "KeyCommands", "HashCommands", "ListCommands",
         "SetCommands", "SortedSetCommands", "GeoCommands", "StreamCommands", "JsonCommands",
         "ScriptingCommands", "RuvioCommands"]
HEADER = "// SPDX-License-Identifier: MIT\n// GENERATED by tools/generate.py. Do not edit by hand.\npackage io.github.salihcantekin.ruvio;\n\n"


def word_for(ident):
    if ident.startswith("JSON_"):
        return "JSON." + ident[5:]
    if ident.startswith("BF_"):
        return "BF." + ident[3:]
    return ident


def gen_cmd():
    idents = set()
    for name in os.listdir(ROOT):
        if name.endswith(".java") and name != "Cmd.java":
            idents.update(re.findall(r"\bCmd\.([A-Z][A-Z0-9_]*)\b", open(os.path.join(ROOT, name)).read()))
    lines = [HEADER, "/** Command words pre-encoded as complete RESP bulk fragments ({@code $3\\r\\nGET\\r\\n}). */\n",
             "final class Cmd {\n    private Cmd() {\n    }\n\n"]
    for ident in sorted(idents):
        lines.append('    static final byte[] %s = RespOut.fragment("%s");\n' % (ident, word_for(ident)))
    lines.append("}\n")
    open(os.path.join(ROOT, "Cmd.java"), "w").write("".join(lines))
    return len(idents)


def split_params(params):
    out, depth, cur = [], 0, ""
    for ch in params:
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


METHOD = re.compile(r"((?:[ \t]*/\*\*(?:(?!\*/).)*\*/\n)?)((?:[ \t]*@\w+\n)*)[ \t]*public (final )?CompletableFuture<", re.S)


def methods(src):
    for m in METHOD.finditer(src):
        i = m.end()
        depth = 1
        while depth:
            if src[i] == "<":
                depth += 1
            elif src[i] == ">":
                depth -= 1
            i += 1
        ret = src[m.end():i - 1]
        rest = src[i:]
        mm = re.match(r"\s*(\w+)\((.*?)\)\s*\{", rest, re.S)
        if not mm:
            continue
        doc = m.group(1)
        annotations = m.group(2)
        yield doc, annotations, ret, mm.group(1), mm.group(2)


def gen_sync():
    body = []
    seen = set()
    count = 0
    for cls in CHAIN:
        src = open(os.path.join(ROOT, cls + ".java")).read()
        body.append("\n    // ---- %s ----\n" % cls)
        for doc, annotations, ret, name, params in methods(src):
            plist = split_params(params)
            sig = (name, tuple(re.sub(r"\s+\w+$", "", p) for p in plist))
            if sig in seen:
                continue
            seen.add(sig)
            count += 1
            names = [re.sub(r".*\s", "", p) for p in plist]
            varargs = any("..." in p for p in plist)
            generic_varargs = any(re.search(r"\b[KV](<[^>]*>)?\.\.\.", p) or re.search(r"GeoValue<V>\.\.\.", p) for p in plist)
            if doc:
                body.append(doc)
            mods = "public final " if generic_varargs else "public "
            if generic_varargs:
                body.append("    @SafeVarargs\n")
            call = "async.%s(%s)" % (name, ", ".join(names))
            if ret == "Void":
                body.append("    %svoid %s(%s) {\n        await(%s);\n    }\n\n" % (mods, name, ", ".join(plist), call))
            else:
                body.append("    %s%s %s(%s) {\n        return await(%s);\n    }\n\n" % (mods, ret, name, ", ".join(plist), call))
    src = HEADER + """import java.util.List;
import java.util.Map;
import java.util.concurrent.CompletableFuture;

/**
 * Blocking facade over {@link RuvioAsync}: every method sends the typed command on the shared
 * multiplexed connection and waits for its reply. Server errors are thrown as
 * {@link RuvioServerException}, socket failures as {@link RuvioConnectionException}.
 */
public abstract class RuvioSyncCommands<K, V> {
    final RuvioAsync<K, V> async;

    RuvioSyncCommands(RuvioAsync<K, V> async) {
        this.async = async;
    }

    abstract <T> T await(CompletableFuture<T> future);
""" + "".join(body).rstrip() + "\n}\n"
    open(os.path.join(ROOT, "RuvioSyncCommands.java"), "w").write(src)
    return count


if __name__ == "__main__":
    print("Cmd words:", gen_cmd())
    print("sync methods:", gen_sync())
